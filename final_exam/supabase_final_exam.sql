-- Function: is_admin (PDF 1 Slide 2)
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1
    FROM public.profiles p
    JOIN public.roles r ON r.id = p.role_id
    WHERE p.id = auth.uid() AND r.role = 'admin'
  );
END;
$$;

-- Function: handle_new_user (PDF 1 Slide 2)
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, email, firstname, lastname, role_id)
  VALUES (
    new.id,
    new.email,
    COALESCE(
      new.raw_user_meta_data->>'firstname',
      split_part(COALESCE(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', new.email), ' ', 1)
    ),
    COALESCE(
      new.raw_user_meta_data->>'lastname',
      split_part(COALESCE(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', ''), ' ', 2)
    ),
    (SELECT id FROM public.roles WHERE role = 'customer' LIMIT 1)
  );
  RETURN new;
END;
$$;

-- Trigger: on_auth_user_created
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Function: place_order (Atomic Checkout Transaction)
CREATE OR REPLACE FUNCTION public.place_order(items JSONB)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  v_user_id UUID;
  v_order_id INT8;
  v_total NUMERIC(12, 2) := 0.00;
  v_item RECORD;
  v_product RECORD;
  v_prod_id INT8;
  v_qty INT8;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'You must be signed in to place an order.';
  END IF;

  -- Ensure user is customer (not admin)
  IF is_admin() THEN
    RAISE EXCEPTION 'Admins cannot place orders.';
  END IF;

  IF jsonb_array_length(items) = 0 THEN
    RAISE EXCEPTION 'Cart is empty.';
  END IF;

  -- 1. Validate stock and calculate total using authoritative database prices
  FOR v_item IN SELECT * FROM jsonb_to_recordset(items) AS x(product_id INT8, quantity INT8)
  LOOP
    v_prod_id := v_item.product_id;
    v_qty := v_item.quantity;

    IF v_qty <= 0 THEN
      RAISE EXCEPTION 'Quantity for product ID % must be greater than zero.', v_prod_id;
    END IF;

    -- Row-level lock to prevent concurrent stock race conditions
    SELECT id, name, price, stock
    INTO v_product
    FROM public.products
    WHERE id = v_prod_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Product with ID % does not exist.', v_prod_id;
    END IF;

    IF v_product.stock < v_qty THEN
      RAISE EXCEPTION 'Insufficient stock for "%". Available: %, Requested: %', v_product.name, v_product.stock, v_qty;
    END IF;

    v_total := v_total + (v_product.price * v_qty);
  END LOOP;

  -- 2. Insert into orders table with status = 'done' (as per requirement)
  INSERT INTO public.orders (user_id, status, total)
  VALUES (v_user_id, 'done', v_total)
  RETURNING id INTO v_order_id;

  -- 3. Deduct stock and save order_items with immutable snapshot of name & unit price
  FOR v_item IN SELECT * FROM jsonb_to_recordset(items) AS x(product_id INT8, quantity INT8)
  LOOP
    v_prod_id := v_item.product_id;
    v_qty := v_item.quantity;

    SELECT id, name, price
    INTO v_product
    FROM public.products
    WHERE id = v_prod_id;

    -- Decrement stock in database
    UPDATE public.products
    SET stock = stock - v_qty
    WHERE id = v_prod_id;

    -- Snapshot into order_items
    INSERT INTO public.order_items (order_id, product_id, product_name, unit_price, quantity)
    VALUES (v_order_id, v_prod_id, v_product.name, v_product.price, v_qty);
  END LOOP;

  RETURN jsonb_build_object(
    'order_id', v_order_id,
    'total', v_total,
    'status', 'done'
  );
END;
$$;

-- Helper Function: make_user_admin
-- Run this in SQL editor to elevate a user to admin: SELECT public.make_user_admin('your-email@example.com');
CREATE OR REPLACE FUNCTION public.make_user_admin(target_email TEXT)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  v_admin_role_id INT8;
  v_updated INT;
BEGIN
  SELECT id INTO v_admin_role_id FROM public.roles WHERE role = 'admin';
  IF v_admin_role_id IS NULL THEN
    RAISE EXCEPTION 'Admin role does not exist.';
  END IF;

  UPDATE public.profiles
  SET role_id = v_admin_role_id
  WHERE email = target_email;

  GET DIAGNOSTICS v_updated = ROW_COUNT;
  IF v_updated > 0 THEN
    RETURN 'User ' || target_email || ' has been granted the admin role.';
  ELSE
    RETURN 'No profile found for ' || target_email || '. Make sure they have signed up first.';
  END IF;
END;
$$;

