-- ------------------------------------------------------------------------------
-- Table: roles
-- Signed out: No access | Customer: Read | Admin: Read
-- ------------------------------------------------------------------------------
CREATE POLICY "roles_read"
  ON public.roles
  FOR SELECT
  TO authenticated
  USING (true);

-- ------------------------------------------------------------------------------
-- Table: profiles
-- Signed out: No access
-- Customer: Read and update own row only, and never the role
-- Admin: Read all profiles
-- ------------------------------------------------------------------------------
CREATE POLICY "profiles_select"
  ON public.profiles
  FOR SELECT
  TO authenticated
  USING (id = auth.uid() OR is_admin());

CREATE POLICY "profiles_customer_update"
  ON public.profiles
  FOR UPDATE
  TO authenticated
  USING (id = auth.uid())
  WITH CHECK (
    id = auth.uid() 
    AND role_id = (SELECT role_id FROM public.profiles WHERE id = auth.uid())
  );

CREATE POLICY "profiles_admin_update"
  ON public.profiles
  FOR UPDATE
  TO authenticated
  USING (is_admin())
  WITH CHECK (is_admin());

-- ------------------------------------------------------------------------------
-- Table: categories
-- Signed out: No access | Customer: Read | Admin: Read, add, edit, delete
-- ------------------------------------------------------------------------------
