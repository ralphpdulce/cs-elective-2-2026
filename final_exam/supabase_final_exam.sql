  ON public.orders
  FOR INSERT
  TO authenticated
  WITH CHECK (user_id = auth.uid());

CREATE POLICY "orders_admin_update_status"
  ON public.orders
  FOR UPDATE
  TO authenticated
  USING (is_admin())
  WITH CHECK (is_admin());

-- ------------------------------------------------------------------------------
-- Table: order_items
-- Signed out: No access | Customer: Read items of own orders only | Admin: Read all
-- ------------------------------------------------------------------------------
CREATE POLICY "order_items_select"
  ON public.order_items
  FOR SELECT
  TO authenticated
  USING (
    is_admin() OR EXISTS (
      SELECT 1 FROM public.orders o
      WHERE o.id = order_items.order_id AND o.user_id = auth.uid()
    )
  );

CREATE POLICY "order_items_insert"
  ON public.order_items
  FOR INSERT
  TO authenticated
  WITH CHECK (
    is_admin() OR EXISTS (
      SELECT 1 FROM public.orders o
      WHERE o.id = order_items.order_id AND o.user_id = auth.uid()
    )
  );

