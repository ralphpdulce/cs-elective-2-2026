-- ------------------------------------------------------------------------------
-- Table: orders
-- Signed out: No access | Customer: Read own orders only | Admin: Read all, update status
-- ------------------------------------------------------------------------------
CREATE POLICY "orders_select"
  ON public.orders
  FOR SELECT
  TO authenticated
  USING (user_id = auth.uid() OR is_admin());

